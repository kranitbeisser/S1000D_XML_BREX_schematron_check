def run_validator(brex_mode, log_dir, config_path=CONFIG_DIR):
    log_path = Path(log_dir)
    if log_path.exists():
        shutil.rmtree(log_path)
    log_path.mkdir(parents=True, exist_ok=True)
    
    cmd = [
        sys.executable,
        str(PROJECT_ROOT / "S1000D_XML_Processor.py"),
        "-i", str(DMS_DIR),
        "-c", str(config_path),
        "--schema-dir", str(PROJECT_ROOT / "config" / "schemas" / "Schemas"),
        "--brex-mode", brex_mode,
        "--no-integrity",
        "-l", str(log_path)
    ]
    
    print(f"Executing: {' '.join(cmd)}")
    res = subprocess.run(cmd, capture_output=True, text=True)
    
    db_files = list(log_path.glob("*.db"))
    if not db_files:
        print("STDOUT:", res.stdout)
        print("STDERR:", res.stderr)
        raise RuntimeError("No SQLite database was generated by the validation process.")
        
    db_file = db_files[0]
    
    # Read database results
    conn = sqlite3.connect(db_file)
    cur = conn.cursor()
    
    cur.execute("""
        SELECT f.filename, e.error_type, e.rule_id, e.message
        FROM Files f
        LEFT JOIN Locations l ON l.file_id = f.id
        LEFT JOIN Errors e ON l.error_id = e.id
    """)
    
    results = {}
    for filename, err_type, rule_id, msg in cur.fetchall():
        if filename not in results:
            results[filename] = []
        if err_type or rule_id or msg:
            results[filename].append({
                'error_type': err_type,
                'rule_id': rule_id,
                'message': msg
            })
            
    conn.close()
    return results

def verify_mode_results(results, manifest):
    failures = []
    print("\n--- Verifying Test Manifest ---")
    print(f"{'Filename':<55} | {'Expected':<8} | {'Actual':<8} | {'Status':<10} | {'Expected Rule Fail':<20}")
    print("-" * 110)
    
    for case in manifest:
        filename = case['filename']
        expected_status = case['expected_status']
        expected_rule = case['rule_id']
        
        file_errors = results.get(filename, [])
        is_invalid = len(file_errors) > 0
        actual_status = "invalid" if is_invalid else "valid"
        
        passed = True
        reason = ""
        
        if expected_status == "valid":
            if is_invalid:
                passed = False
                reason = f"Should have passed but failed with: {[e['rule_id'] for e in file_errors]}"
        else:
            # Expected to fail
            if not is_invalid:
                passed = False
                reason = f"Should have failed rule '{expected_rule}' but passed successfully."
            else:
                # Check if the expected rule matches at least one of the recorded errors
                failed_rules = [e['rule_id'] for e in file_errors]
                if expected_rule not in failed_rules:
                    passed = False
                    reason = f"Failed, but not for the expected rule '{expected_rule}'. Actual failures: {failed_rules}"
                    
        status_str = "PASS" if passed else "FAIL"
        expected_rule_str = expected_rule if expected_rule else "None"
        print(f"{filename:<55} | {expected_status:<8} | {actual_status:<8} | {status_str:<10} | {expected_rule_str:<20}")
        if not passed:
            print(f"  [ERROR] {reason}")
            failures.append((filename, reason))
            
    return failures

